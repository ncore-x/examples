integers = [1, 2, 3]
for index, value in enumerate(integers, start=1):
    print(f"Index: {index}, Value: {value}")

# Output:
# Index: 1, Value: 1
# Index: 2, Value: 2
# Index: 3, Value: 3

# Этот фрагмент перебирает список integers и на каждой итерации получает пару(индекс, значение) через встроенную функцию enumerate. enumerate превращает итерируемый объект в итератор, возвращающий кортежи(index, value)
# по умолчанию нумерация начинается с 0, но здесь вторым аргументом передано 1, поэтому индексы идут с 1.

# В цикле for используется распаковка кортежа на переменные index и value, а затем строковый литерал f-string подставляет их в вывод: print(f"Index: {index}, Value: {value}") печатает каждую пару на новой строке(print по умолчанию добавляет перевод строки).
